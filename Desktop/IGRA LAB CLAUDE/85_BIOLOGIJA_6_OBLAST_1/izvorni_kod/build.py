def blank(w=34):
    return f'<span class="blank" style="width:{w}mm"></span>'


def lines(n, grow=False, labels=None):
    g = ' data-grow="1"' if grow else ""
    if labels:
        rows = "".join(f'<div class="ln">{l}</div>' for l in labels)
        rows += '<div class="ln"></div>' * (n - len(labels))
        return f'<div class="lines lab"{g}>{rows}</div>'
    return f'<div class="lines"{g}>' + '<div class="ln"></div>' * n + "</div>"


def task(n, kind, body):
    return (f'<div class="task" data-id="{n}"><div class="th"><div class="tn">{n}</div>'
            f'<div class="tk">{kind}</div></div>{body}</div>')


def p(t, cls="tt"):
    return f'<p class="{cls}">{t}</p>'


def hint(t):
    return f'<p class="hint">{t}</p>'


def chips(words, boxed=False):
    return f'<div class="chips{" boxed" if boxed else ""}">' + "".join(f"<span>{w}</span>" for w in words) + "</div>"


def opts(items, col=False, gap=None):
    st = f' style="gap:{gap}mm"' if gap else ""
    return (f'<div class="opts{" col" if col else ""}"{st}>'
            + "".join(f"<span><b>{a})</b>{t}</span>" for a, t in items) + "</div>")


def match(left, right, lw=52):
    l = "".join(f'<div><span>{x}</span><span class="box"></span></div>' for x in left)
    r = "".join(f"<div><b>{a})</b>{t}</div>" for a, t in right)
    return (f'<div class="match" style="grid-template-columns:{lw}mm 1fr"><div class="left">{l}</div>'
            f'<div class="right">{r}</div></div>')


def tf(rows):
    return '<div class="tf">' + "".join(f'<div class="row"><span>{r}</span><span class="box"></span></div>' for r in rows) + "</div>"


def sub(t):
    return f'<p class="sublab">{t}</p>'


def flow(parts):
    out = []
    for kind, v in parts:
        if kind == "c":
            out.append(f'<div class="fc">{v}</div>')
        elif kind == "b":
            w, n = v
            out.append(f'<div class="fb" style="width:{w}mm">' + '<div class="ln"></div>' * n + "</div>")
        elif kind == "x":
            out.append(f'<div class="fx"><small>{v}</small><span>→</span></div>')
        else:
            out.append(f'<div class="ar">{v}</div>')
    return '<div class="flow">' + "".join(out) + "</div>"


def labels(n):
    return '<div class="labels">' + "".join(f'<div class="lr"><span class="nc">{i}</span><i></i></div>' for i in range(1, n + 1)) + "</div>"


def fig(s):
    return f'<div class="fig">{s}</div>'


PLUS, MINUS = '<span class="sg p"></span>', '<span class="sg"></span>'


def remember(t):
    return f'<div class="remember"><h3>ЗАПАМТИ</h3><p>{t}</p></div>'


def home(paras, icon=""):
    ps = "".join(f'<p{" class=rule" if r else ""}>{t}</p>' for t, r in paras)
    return f'<div class="home"><div><h3>КОД КУЋЕ</h3>{ps}</div><div class="ico">{icon}</div></div>'


